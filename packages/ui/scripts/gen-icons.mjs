// Run: node packages/ui/scripts/gen-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(join(here, "..", "package.json"));
const svgDir = join(dirname(require.resolve("framework7-icons/package.json")), "svg");

const names = [
  "house_fill", "chart_pie_fill", "doc_text_fill", "square_grid_2x2_fill", "chart_bar_fill", "chart_bar_alt_fill", "graph_square_fill",
  "clock_fill", "gear_alt_fill", "ellipsis", "ellipsis_circle_fill", "arrow_down", "arrow_up", "arrow_right_arrow_left",
  "plus", "minus", "creditcard_fill", "tray_fill", "flag_fill", "star_fill", "lock_fill", "lock_open_fill",
  "umbrella_fill", "airplane", "car_fill", "book_fill", "gift_fill", "heart_fill", "bag_fill", "cart_fill",
  "briefcase_fill", "bolt_fill", "drop_fill", "phone_fill", "wifi", "tv_fill", "person_2_fill", "person_fill",
  "person_crop_circle_fill", "checkmark_alt", "checkmark_circle_fill", "xmark", "xmark_circle_fill",
  "doc_on_doc_fill", "doc_on_doc", "square_arrow_up", "square_arrow_up_fill", "qrcode", "link", "chevron_right", "chevron_left",
  "chevron_down", "chevron_up", "exclamationmark_triangle_fill", "info_circle_fill", "info_circle", "pencil", "trash_fill", "globe",
  "moon_fill", "sun_max_fill", "arrow_2_circlepath", "bell_fill", "sparkles", "calendar", "hourglass", "eye_fill",
  "eye_slash_fill", "paperplane_fill", "shield_fill", "checkmark_shield_fill", "hand_raised_fill", "power",
  "arrow_up_right", "arrow_up_right_square", "graph_square_fill", "percent", "timer_fill", "list_bullet", "search",
  "chat_bubble_fill", "lock_shield_fill", "wand_stars", "cube_fill", "arrow_down_doc_fill", "keyboard",
  "delete_left_fill", "delete_left", "building_2_fill", "house_alt_fill", "envelope_fill", "circle_fill",
];

const out = {};
for (const n of names) {
  const svg = readFileSync(join(svgDir, `${n}.svg`), "utf8");
  const vb = /viewBox="([^"]+)"/.exec(svg)?.[1] ?? "0 0 56 56";
  const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim().replace(/(\.\d)\d+/g, "$1");
  out[n] = { vb, body };
}
const file = `/* eslint-disable */
// AUTO-GENERATED by scripts/gen-icons.mjs from framework7-icons (MIT, (c) Vladimir Kharlampidi). Do not edit.
export const glyphs = ${JSON.stringify(out, null, 0).replace(/},"/g, '},\n  "')} as const;
export type GlyphName = keyof typeof glyphs;
`;
writeFileSync(join(here, "..", "src", "icons", "glyphs.ts"), file);
console.log("wrote", Object.keys(out).length, "glyphs");
