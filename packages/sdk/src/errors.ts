const FAMILY: Array<[RegExp, string]> = [
  [/^E_AGENT_/, "E_AGENT_SCOPE"], [/^E_CAP_/, "E_AGENT_CAP"], [/^E_CIRCLE_|^E_AJO_/, "E_CIRCLE_STATUS"], [/^E_NAME_/, "E_NAME_INVALID"], [/^E_LOCK/, "E_LOCKED"],
  [/^E_EARN_/, "E_EARN_PAUSED"], [/^E_BILL_/, "E_BILL_NOT_FOUND"], [/^E_PROPOSAL_/, "E_PROPOSAL_CLOSED"],
];

export const ERROR_CODES: readonly string[] = Object.keys(M);

/** Accepts a code ("E_LOCKED") or any message containing one ("Smart contract panicked: E_LOCKED: pot is locked…"). */
export function friendlyError(codeOrMessage: string): FriendlyError {
  const code = /\b(E_[A-Z0-9_]+)\b/.exec(codeOrMessage ?? "")?.[1];
  if (code) {
    const hit = M[code] ?? (() => { const fam = FAMILY.find(([re]) => re.test(code)); return fam ? M[fam[1]] : undefined; })();
    if (hit) return { code, title: hit[0], next: hit[1] };
    return { code, title: "That didn't go through.", next: "Nothing was changed. Try again, or contact support with this code." };
  }
  if (/NotEnoughBalance|LackBalanceForState|allowance/i.test(codeOrMessage)) return { code: "E_NO_GAS", title: M.E_NO_GAS![0], next: M.E_NO_GAS![1] };
  if (/fetch failed|ECONNREFUSED|timeout|network/i.test(codeOrMessage)) return { code: "E_RPC", title: M.E_RPC![0], next: M.E_RPC![1] };
  return { code: "E_UNKNOWN", title: "Something went wrong.", next: "Nothing was changed. Try again in a moment." };
}
